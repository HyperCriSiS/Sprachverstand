// Hier ist ein reines Personenmapping ausdrücklich nicht freigegeben.
const negativeBasen = [
  "edamer",
  "bernhardiner",
  "bettwärmer",
  "hammer",
  "bestseller",
  "regenschauer",
  "zauber",
  "buhler",
  "neunziger",
  "neunundvierziger",
  "hindenburger",
  "aaseestädterfirma",
  "nutzniesser"
] as const;

describe("Lexikon-Welle 86: 550 geprüfte Herkunfts- und Einwohnerbezeichnungen", () => {
  it("enthält den deduplizierten Exaktbestand", () => {
    expect(basen).toHaveLength(550);
    expect(new Set(basen).size).toBe(550);
    expect(reviewedPersonFormCountWave86).toBe(550);
  });

  it.each(basen)("prüft für %s Singular, Plural, Femininform und Kasus", (basis) => {
    const feminin = `${basis}in`;
    expect(getReviewedPersonFormsWave86(basis)).toEqual({
      plural: basis,
      singular: basis,
      feminineSingular: feminin,
      obliqueSingular: basis,
      genitiveSingular: `${basis}s`
    });
    expect(mappedPluralSeparatorsRule.apply(`${basis}:innen`)).toEqual({
      text: basis,
      replacements: 1
    });
    expect(mapMappedSingularPair(basis, feminin)).toBe(basis);
    expect(mapMappedSingularPair(feminin, basis)).toBe(basis);
    for (const kasus of ["nominative", "accusative", "dative"] as const) {
      expect(mapMappedSingular(basis, kasus)).toBe(basis);
    }
    expect(mapMappedSingular(basis, "genitive")).toBe(`${basis}s`);
  });

  it.each(negativeBasen)("schließt die zweifelhafte Basis %s aus", (basis) => {
    expect(getReviewedPersonFormsWave86(basis)).toBeUndefined();
  });

  it("lässt normale, unmarkierte Wörter unverändert", () => {
    expect(mappedPluralSeparatorsRule.apply("Aaseestädter")).toEqual({
      text: "Aaseestädter",
      replacements: 0
    });
    expect(getReviewedPersonFormsWave86("aaseestädterfirma")).toBeUndefined();
  });
});