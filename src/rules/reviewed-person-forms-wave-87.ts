export const reviewedPersonFormCountWave87 = geprueftePersonenbasen.size;

export function getReviewedPersonFormsWave87(
  normalizedBase: string
): GeneratedPersonForms | undefined {
  if (!geprueftePersonenbasen.has(normalizedBase)) {
    return undefined;
  }

  return {
    plural: normalizedBase,
    singular: normalizedBase,
    feminineSingular: `${normalizedBase}in`,
    obliqueSingular: normalizedBase,
    genitiveSingular: `${normalizedBase}s`
  };
}
